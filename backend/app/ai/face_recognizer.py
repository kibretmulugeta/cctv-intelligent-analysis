"""
Face recognizer: compares face embeddings to enrolled identities.
Works with embeddings generated by FaceDetector (InsightFace).
Falls back gracefully if no enrolled identities exist or backend is unavailable.
"""
from __future__ import annotations
import logging
import numpy as np
from typing import List, Dict, Any, Optional, Tuple
import io

logger = logging.getLogger(__name__)


def _cosine_similarity(a: np.ndarray, b: np.ndarray) -> float:
    """Compute cosine similarity between two embedding vectors."""
    a = a.flatten()
    b = b.flatten()
    norm_a = np.linalg.norm(a)
    norm_b = np.linalg.norm(b)
    if norm_a == 0 or norm_b == 0:
        return 0.0
    return float(np.dot(a, b) / (norm_a * norm_b))


class FaceRecognizer:
    """
    Compares face embeddings against a set of enrolled identities.
    Enrolled embeddings are loaded from the database at runtime.
    """

    def __init__(self, threshold: float = 0.50):
        self.threshold = threshold
        # In-memory cache: {face_id: {"name": str, "embeddings": [np.ndarray]}}
        self._enrolled: Dict[str, Dict[str, Any]] = {}

    def load_enrolled(self, enrolled_faces: List[Dict[str, Any]]) -> None:
        """
        Load enrolled faces from database records.

        Args:
            enrolled_faces: list of {face_id, name, embeddings: [bytes]}
        """
        self._enrolled.clear()
        for face in enrolled_faces:
            embeddings = []
            for emb_bytes in face.get("embeddings", []):
                try:
                    arr = np.load(io.BytesIO(emb_bytes))
                    embeddings.append(arr)
                except Exception as e:
                    logger.debug(f"Failed to load embedding: {e}")
            if embeddings:
                self._enrolled[face["face_id"]] = {
                    "name": face["name"],
                    "embeddings": embeddings,
                }
        logger.info(f"Loaded {len(self._enrolled)} enrolled identities into recognizer")

    def recognize(self, embedding: Optional[np.ndarray]) -> Dict[str, Any]:
        """
        Attempt to recognize a face embedding against enrolled identities.

        Returns:
            {face_id, name, confidence, matched}
        """
        if embedding is None or len(self._enrolled) == 0:
            return {"face_id": None, "name": "Unknown", "confidence": 0.0, "matched": False}

        best_match_id = None
        best_match_name = "Unknown"
        best_score = 0.0

        for face_id, data in self._enrolled.items():
            for enrolled_emb in data["embeddings"]:
                score = _cosine_similarity(embedding, enrolled_emb)
                if score > best_score:
                    best_score = score
                    best_match_id = face_id
                    best_match_name = data["name"]

        matched = best_score >= self.threshold
        return {
            "face_id": best_match_id if matched else None,
            "name": best_match_name if matched else "Unknown",
            "confidence": round(best_score, 4),
            "matched": matched,
        }

    def embedding_to_bytes(self, embedding: np.ndarray) -> bytes:
        """Serialize a numpy embedding to bytes for database storage."""
        buf = io.BytesIO()
        np.save(buf, embedding)
        return buf.getvalue()

    def bytes_to_embedding(self, data: bytes) -> np.ndarray:
        """Deserialize bytes back to numpy embedding."""
        return np.load(io.BytesIO(data))

    def has_enrolled(self) -> bool:
        return len(self._enrolled) > 0
